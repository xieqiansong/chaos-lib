-- ============================================================
-- 2026-09-12: SSH 端口转发（ssh-port-forward 变更）
-- 新增 ssh_connections 表保存 SSH 连接信息（密码或私钥）；
-- port_forwarding 增加 ssh_connection_id（关联 SSH 连接）与 remark 列。
-- 凭据列仅后端建立 SSH 隧道时使用：API 一律不回显，日志不记录。
-- 对应模型：internal/portfwd.SshConnection、internal/portfwd.PortForwarding
-- ============================================================

CREATE TABLE public.ssh_connections (
    id          integer NOT NULL,
    name        text,
    host        text,
    port        bigint,
    username    text,
    auth_type   text,
    password    text,
    private_key text,
    passphrase  text,
    remark      text
);
COMMENT ON TABLE public.ssh_connections IS 'SSH 连接信息：端口转发经此连接建立 SSH 隧道（本地转发，等价 ssh -L）';
COMMENT ON COLUMN public.ssh_connections.name IS '连接名称，供选择与展示';
COMMENT ON COLUMN public.ssh_connections.host IS 'SSH 服务器主机';
COMMENT ON COLUMN public.ssh_connections.port IS 'SSH 服务器端口，默认 22';
COMMENT ON COLUMN public.ssh_connections.username IS 'SSH 用户名';
COMMENT ON COLUMN public.ssh_connections.auth_type IS '认证方式：password（密码）/ key（私钥）';
COMMENT ON COLUMN public.ssh_connections.password IS '密码认证的密码；仅后端建连使用，API 不回显、日志不记录';
COMMENT ON COLUMN public.ssh_connections.private_key IS '私钥认证的私钥内容（PEM）；仅后端建连使用，API 不回显、日志不记录';
COMMENT ON COLUMN public.ssh_connections.passphrase IS '私钥口令（可选）；仅后端建连使用，API 不回显、日志不记录';
COMMENT ON COLUMN public.ssh_connections.remark IS '备注';

ALTER TABLE public.ssh_connections ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.ssh_connections_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

ALTER TABLE ONLY public.ssh_connections ADD CONSTRAINT ssh_connections_pkey PRIMARY KEY (id);

ALTER TABLE public.port_forwarding ADD COLUMN IF NOT EXISTS ssh_connection_id integer;
ALTER TABLE public.port_forwarding ADD COLUMN IF NOT EXISTS remark text;
COMMENT ON COLUMN public.port_forwarding.ssh_connection_id IS '关联的 SSH 连接 id（ssh_connections.id）';
COMMENT ON COLUMN public.port_forwarding.remark IS '端口转发规则备注';

-- ============================================================
-- 2026-09-12: SSH 远程转发（ssh-remote-forward 变更）
-- port_forwarding 增加 direction 与 bind_address 两列：
--   direction = local：在本机监听（等价 ssh -L），bind_address 缺省 0.0.0.0；
--   direction = remote：在 SSH 服务器侧监听（等价 ssh -R），bind_address 缺省 127.0.0.1。
-- 方向为空的历史数据一律视为 local（本次回填显式化，读路径也做了兜底）。
-- 对应模型：internal/portfwd.PortForwarding
-- ============================================================

ALTER TABLE public.port_forwarding ADD COLUMN IF NOT EXISTS direction text;
ALTER TABLE public.port_forwarding ADD COLUMN IF NOT EXISTS bind_address text;
COMMENT ON COLUMN public.port_forwarding.direction IS '转发方向：local（本机监听，等价 ssh -L）/ remote（SSH 服务器侧监听，等价 ssh -R）；空值视为 local';
COMMENT ON COLUMN public.port_forwarding.bind_address IS '监听地址：local 为本机监听地址（缺省 0.0.0.0），remote 为 SSH 服务器侧监听地址（缺省 127.0.0.1）';

UPDATE public.port_forwarding SET direction = 'local' WHERE direction IS NULL OR direction = '';

-- ============================================================
-- 2026-09-15: 直接转发（direct 方向）
-- port_forwarding.direction 新增取值 direct：
--   直接转发 = 本机监听（监听地址缺省 0.0.0.0），接入流量经纯 TCP 直连目标（host:port），不经 SSH 隧道；
--   因此 direct 规则不关联 ssh_connection_id（无对应连接时本列存 0），其余字段含义与 local 一致。
-- 列结构无需变更（direction 已是 text），此处仅补充取值说明，便于人工维护。
-- 对应模型：internal/portfwd.PortForwarding
-- ============================================================

COMMENT ON COLUMN public.port_forwarding.direction IS '转发方向：local（本机监听，等价 ssh -L）/ remote（SSH 服务器侧监听，等价 ssh -R）/ direct（本机监听直连目标，纯 TCP，不经 SSH）；空值视为 local';


-- ============================================================
-- 2026-09-13: MQTT 多节点消息同步（mqtt-cluster-sync 变更）
