COMMENT ON TABLE public.mqtt_sync_messages IS 'MQTT 多节点同步消息落库表：每个 channel 仅界面展示最新一条，旧消息保留';
COMMENT ON COLUMN public.mqtt_sync_messages.msg_id IS '线上报文 id（uuid），全局唯一，用于去重';
COMMENT ON COLUMN public.mqtt_sync_messages.node_id IS '发送方节点标识';
COMMENT ON COLUMN public.mqtt_sync_messages.channel IS 'topic（不含前缀），如 broadcast';
COMMENT ON COLUMN public.mqtt_sync_messages.payload IS '消息内容（本期明文，加密为后续变更）';
COMMENT ON COLUMN public.mqtt_sync_messages.is_deleted IS '软删除标记';

ALTER TABLE public.mqtt_sync_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.mqtt_sync_messages_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
