-- 2026-09-19: 常用书签独立实现（frequent-bookmarks 变更）
-- 新增 bookmarks 表，由扩展周期性备份浏览器书签树（扁平快照）；
-- 常用书签 = bookmarks 关联 browser_histories 的访问次数，按访问频率降序分页返回（默认 20）。
-- 对应模型：internal/proxy.Bookmark；接口 GET /frequentBookmarks、POST /bookmarks
-- ============================================================

CREATE TABLE public.bookmarks (
    id         text    NOT NULL,
    parent_id  text,
    title      text,
    url        text,
    is_folder  boolean DEFAULT false,
    sort_index integer DEFAULT 0,
    date_added bigint
);
COMMENT ON TABLE public.bookmarks IS '浏览器书签扁平快照：由扩展周期备份；url 非空为书签叶子，空为文件夹';
COMMENT ON COLUMN public.bookmarks.id IS '浏览器书签节点原始 id（稳定唯一）';
COMMENT ON COLUMN public.bookmarks.parent_id IS '父文件夹 id';
COMMENT ON COLUMN public.bookmarks.title IS '书签/文件夹标题';
COMMENT ON COLUMN public.bookmarks.url IS '书签 URL；文件夹为空';
COMMENT ON COLUMN public.bookmarks.is_folder IS '是否为文件夹';
COMMENT ON COLUMN public.bookmarks.sort_index IS '同级中的顺序';
COMMENT ON COLUMN public.bookmarks.date_added IS '书签创建时间戳（毫秒）';

ALTER TABLE ONLY public.bookmarks ADD CONSTRAINT bookmarks_pkey PRIMARY KEY (id);
CREATE INDEX idx_bookmarks_url ON public.bookmarks USING btree (url) WHERE (url <> '');

