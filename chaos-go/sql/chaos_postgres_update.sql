ALTER TABLE ONLY public.mqtt_sync_messages ADD CONSTRAINT mqtt_sync_messages_pkey PRIMARY KEY (id);
CREATE UNIQUE INDEX idx_mqtt_sync_messages_msg_id ON public.mqtt_sync_messages USING btree (msg_id) WHERE (is_deleted = false);

CREATE TABLE public.mqtt_sync_node (
    id          integer   NOT NULL,
    node_id     text      NOT NULL,
    created_at  timestamp
);
COMMENT ON TABLE public.mqtt_sync_node IS '本机节点标识：首次启动生成并持久化，全程稳定';
COMMENT ON COLUMN public.mqtt_sync_node.node_id IS '节点唯一标识（uuid），用作回声丢弃与界面「本机」标识';

ALTER TABLE public.mqtt_sync_node ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
