(
    id                 VARCHAR PRIMARY KEY,
    history_id         VARCHAR NOT NULL,
    is_local           BOOLEAN,
    referring_visit_id VARCHAR,
    transition         TEXT,
    visit_id           VARCHAR,
    visit_time         DOUBLE PRECISION,
    is_deleted         BOOLEAN DEFAULT FALSE
    -- 建立外键约束
    -- CONSTRAINT fk_browser_history FOREIGN KEY (history_id) REFERENCES browser_history (id)
