CREATE TABLE IF NOT EXISTS browser_histories
(
    id              VARCHAR PRIMARY KEY,
    last_visit_time DOUBLE PRECISION NOT NULL,
    title           TEXT,
    type_count      INTEGER DEFAULT 0,
    url             TEXT,
    visit_count     INTEGER DEFAULT 0,
    is_deleted      BOOLEAN DEFAULT FALSE
);


